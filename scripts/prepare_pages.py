"""Prepara los archivos estáticos de Blossom para GitHub Pages, sin dependencias."""

from pathlib import Path
import base64
import json
import os
import shutil
import tempfile
from urllib.parse import urlparse


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "_site"
MARKER = "Generated by scripts/prepare_pages.py for Blossom Brew Lab.\n"


def cloud_config():
    url = os.environ.get("BLOSSOM_SUPABASE_URL", "").strip().rstrip("/")
    key = os.environ.get("BLOSSOM_SUPABASE_PUBLISHABLE_KEY", "").strip()
    if not url and not key:
        return None
    parsed = urlparse(url)
    if parsed.scheme != "https" or not parsed.netloc or parsed.username or parsed.password or parsed.path or parsed.query or parsed.fragment:
        raise SystemExit("La dirección de Supabase debe ser un origen HTTPS válido.")
    public = key.startswith("sb_publishable_")
    if not public and key.startswith("eyJ"):
        try:
            payload = key.split(".")[1]
            public = json.loads(base64.urlsafe_b64decode(payload + "=" * (-len(payload) % 4))).get("role") == "anon"
        except (ValueError, IndexError):
            public = False
    if not public:
        raise SystemExit("Solo se admite una clave pública publishable/anon. No publiques claves de servidor.")
    return {"url": url, "publishableKey": key}


def main():
    config = cloud_config()
    if OUTPUT.is_symlink():
        raise SystemExit("_site es un enlace simbólico; no se reemplazará.")
    if OUTPUT.exists():
        marker = OUTPUT / ".nojekyll"
        if not marker.is_file() or marker.read_text() != MARKER:
            raise SystemExit("_site ya existe y no fue generado por este script. Conserva esos archivos antes de continuar.")

    # Copy to a new directory first; a failed copy leaves an earlier build intact.
    with tempfile.TemporaryDirectory(prefix=".blossom-site-", dir=ROOT) as temporary:
        staging = Path(temporary) / "site"
        staging.mkdir()
        shutil.copy2(ROOT / "index.html", staging / "index.html")
        for directory in ["assets", "src"]:
            shutil.copytree(ROOT / directory, staging / directory)
        if config:
            (staging / "src" / "cloud-config.js").write_text(
                'globalThis.BlossomLab ??= {};\n'
                'globalThis.BlossomLab.cloudConfig = Object.freeze('
                + json.dumps(config, ensure_ascii=True) + ');\n'
            )
        (staging / ".nojekyll").write_text(MARKER)
        if OUTPUT.exists():
            shutil.rmtree(OUTPUT)
        staging.rename(OUTPUT)
    print(f"Sitio preparado en {OUTPUT}")


if __name__ == "__main__":
    main()
